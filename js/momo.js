  function hash(str) {
    let h = 2166136261;
    for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
    return h >>> 0;
  }

  /** 按日期选当天的一句：一年里的每一天各用一句，一年内不重复；每年的起点错开一点 */
  function quoteOf(date) {
    const y = date.getFullYear();
    const dayOfYear = Math.round((Date.UTC(y, date.getMonth(), date.getDate()) - Date.UTC(y, 0, 1)) / 86400000);
    return QUOTES[(dayOfYear + (hash(String(y)) % QUOTES.length)) % QUOTES.length];
  }

